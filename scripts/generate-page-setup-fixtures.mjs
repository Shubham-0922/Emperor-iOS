#!/usr/bin/env node
// Regenerates the page-setup golden cases from the platform's own source.
//
//   node scripts/generate-page-setup-fixtures.mjs <path-to-emperor-ai> [--check]
//
// The server-rendered PDF export sends the paper it is laid out on (`POST /print-pdf`,
// `pageSetup`). The web builds it with `normalizePageSetup` (src/lib/pageSetup.js), which is pure
// and is imported as it stands. `PageSetup()` in this client must encode to the A4 case.
//
// Writes Tests/EmperorCoreTests/Resources/parity/14-X/page-setup.json. `--check` writes nothing
// and exits 1 if the committed file differs.

import { pathToFileURL, fileURLToPath } from 'node:url'
import fs from 'node:fs'
import path from 'node:path'

const platform = process.argv[2]
const checkOnly = process.argv.includes('--check')
if (!platform || !fs.existsSync(path.join(platform, 'src/lib/pageSetup.js'))) {
  console.error('usage: generate-page-setup-fixtures.mjs <path-to-emperor-ai> [--check]')
  process.exit(2)
}
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)),
  '../Tests/EmperorCoreTests/Resources/parity/14-X/page-setup.json')

const PS = await import(pathToFileURL(path.join(platform, 'src/lib/pageSetup.js')).href)
if (typeof PS.normalizePageSetup !== 'function') {
  console.error('normalizePageSetup not found in src/lib/pageSetup.js — the platform has changed shape')
  process.exit(1)
}

const json = JSON.stringify({
  note: 'Generated by scripts/generate-page-setup-fixtures.mjs from the platform; do not edit.',
  a4: PS.normalizePageSetup({ size: 'a4' }),
  letter: PS.normalizePageSetup({ size: 'letter' }),
  default: PS.normalizePageSetup(null),
}, null, 2) + '\n'

if (checkOnly) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : ''
  if (current !== json) { console.error('page-setup.json is out of date with the platform'); process.exit(1) }
  console.log('page-setup.json matches the platform')
} else {
  fs.mkdirSync(path.dirname(out), { recursive: true })
  fs.writeFileSync(out, json)
  console.log(`wrote 3 page setups to ${path.relative(process.cwd(), out)}`)
}
